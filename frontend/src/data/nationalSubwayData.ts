// 특정 노선에서 퀴즈 문제를 생성하는 폴백/로컬 제너레이터
export function generateQuizFromSequences(
    allowedLineIds: number[] = [],
    excludeStationNames: string[] = []
): GeneratedQuiz {
    const validLines = allowedLineIds.length > 0
        ? SUBWAY_LINES.filter((l) => allowedLineIds.includes(l.id))
        : SUBWAY_LINES;

    const chosenLine = validLines[Math.floor(Math.random() * validLines.length)] || SUBWAY_LINES[1]; // 기본 2호선
    const stations = LINE_STATION_SEQUENCES[chosenLine.id] || LINE_STATION_SEQUENCES[2];

    const isCircular = chosenLine.id === 2; // 2호선은 순환선
    const availableIndices = stations
        .map((name, idx) => ({ name, idx }))
        .filter((item) => !excludeStationNames.includes(item.name));

    const selectedPool = availableIndices.length > 0 ? availableIndices : stations.map((name, idx) => ({ name, idx }));
    const chosen = selectedPool[Math.floor(Math.random() * selectedPool.length)];
    const targetIdx = chosen.idx;
    const targetName = chosen.name;
    const total = stations.length;

    const getStationAt = (index: number): string | null => {
        if (isCircular) {
            const wrapped = ((index % total) + total) % total;
            return stations[wrapped];
        }
        if (index < 0 || index >= total) return null;
        return stations[index];
    };

    return {
        target_station_id: getStationId(chosenLine.id, targetIdx),
        target_station_name: targetName,
        line_name: chosenLine.name,
        color_code: chosenLine.color,
        left_2: getStationAt(targetIdx - 2),
        left_1: getStationAt(targetIdx - 1),
        right_1: getStationAt(targetIdx + 1),
        right_2: getStationAt(targetIdx + 2),
    };
}
